import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const graphPath = path.join(repositoryRoot, 'preset-graph.json');
const outputPath = path.join(repositoryRoot, 'src', 'shared', 'generated-preset-graph.ts');
const expectedModes = ['A', 'B', 'C', 'AA', 'BB', 'CA'];
const expectedQualities = ['M', 'VL', 'UL'];
const allowedSteps = ['ClampHighlights', 'Restore', 'RestoreSoft', 'Upscale', 'DenoiseUpscale'];

function fail(message) {
  throw new Error(`Invalid preset-graph.json: ${message}`);
}

function equalArrays(left, right) {
  return left.length === right.length && left.every((value, index) => value === right[index]);
}

function validateGraph(graph) {
  if (!graph || typeof graph !== 'object' || graph.schemaVersion !== 1) {
    fail('schemaVersion must be 1');
  }
  if (!graph.modes || typeof graph.modes !== 'object' || Array.isArray(graph.modes)) {
    fail('modes must be an object');
  }
  const modes = Object.keys(graph.modes);
  if (!equalArrays(modes, expectedModes)) {
    fail(`modes must be ${expectedModes.join(', ')} in canonical order`);
  }
  if (!Array.isArray(graph.qualities) || !equalArrays(graph.qualities, expectedQualities)) {
    fail(`qualities must be ${expectedQualities.join(', ')}`);
  }
  for (const mode of modes) {
    const steps = graph.modes[mode];
    if (!Array.isArray(steps) || steps.length === 0 || steps[0] !== 'ClampHighlights') {
      fail(`${mode} must be a non-empty pipeline beginning with ClampHighlights`);
    }
    for (const step of steps) {
      if (!allowedSteps.includes(step)) fail(`${mode} contains unsupported step ${String(step)}`);
    }
  }
}

const graph = JSON.parse(await readFile(graphPath, 'utf8'));
validateGraph(graph);

const source = `// Generated by scripts/generate-preset-graph.mjs from preset-graph.json.\n`
  + `// Do not edit this file directly.\n\n`
  + `export const ANIME4K_MODES = ${JSON.stringify(expectedModes)} as const;\n`
  + `export type Anime4KMode = (typeof ANIME4K_MODES)[number];\n\n`
  + `export const QUALITY_TIERS = ${JSON.stringify(expectedQualities)} as const;\n`
  + `export type QualityTier = (typeof QUALITY_TIERS)[number];\n\n`
  + `export type PresetStep = ${allowedSteps.map(step => `'${step}'`).join(' | ')};\n\n`
  + `export const OFFICIAL_PRESET_GRAPHS = ${JSON.stringify(graph.modes, null, 2)} as const satisfies `
  + `Record<Anime4KMode, readonly PresetStep[]>;\n`;

const checkOnly = process.argv.includes('--check');
let current = null;
try {
  current = await readFile(outputPath, 'utf8');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (checkOnly) {
  if (current !== source) {
    throw new Error('src/shared/generated-preset-graph.ts is missing or stale');
  }
  console.log('Preset graph generated output is current.');
} else {
  if (current !== source) await writeFile(outputPath, source, 'utf8');
  console.log('Generated TypeScript preset graph from preset-graph.json.');
}
